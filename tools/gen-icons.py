"""Generate Flymex icon glyph data from the glyphs exported out of Flyme's icon fonts.

Usage: python -I tools/gen-icons.py <glyphs.json> <out.ts>
"""
import json, sys, re

FLYME_ICON_NAMES = {
    "U+E145": "add",
    "U+E14C": "close",
    "U+E2EA": "arrow-down",
    "U+E409": "arrow-next",
    "U+E431": "collections",
    "U+E5C4": "arrow-back",
    "U+E5CD": "check",
    "U+E5D3": "more-horiz",
    "U+E5D4": "more-vert",
    "U+E80D": "share",
    "U+E872": "info",
    "U+E87D": "star",
    "U+E87E": "favorite",
    "U+E92E": "delete",
}

def main(src, out):
    data = json.load(open(src, encoding="utf-8"))
    lines = [
        "// AUTO-GENERATED by tools/gen-icons.py — glyph outlines extracted from Flyme's",
        "// own icon fonts (FlymeIcon-Light.otf / FlymeIcon-Thin.otf / iconfont.ttf).",
        "// Do not edit by hand.",
        "",
        "export interface IconGlyph {",
        "  /** SVG path data in the glyph's own coordinate system (y grows downward, viewBox 0 0 upm upm). */",
        "  d: string;",
        "  /** Advance width in font units. */",
        "  advance: number;",
        "}",
        "",
        "export interface IconFontData {",
        "  unitsPerEm: number;",
        "  ascent: number;",
        "  descent: number;",
        "  glyphs: Record<string, IconGlyph>;",
        "}",
        "",
    ]
    for key, var in (("flymeicon_light", "flymeIconLight"), ("flymeicon_thin", "flymeIconThin"), ("iconfont", "flymeIconFont")):
        src_font = data[key]
        lines.append(f"export const {var}: IconFontData = {{")
        lines.append(f"  unitsPerEm: {src_font['unitsPerEm']},")
        lines.append(f"  ascent: {src_font['ascent']},")
        lines.append(f"  descent: {src_font['descent']},")
        lines.append("  glyphs: {")
        for cp, g in sorted(src_font["glyphs"].items()):
            lines.append(f"    {json.dumps(cp)}: {{ d: {json.dumps(g['d'])}, advance: {g['advance']} }},")
        lines.append("  },")
        lines.append("};")
        lines.append("")
    lines.append("/** Glyph name -> codepoint in FlymeIcon-Light/Thin. */")
    lines.append("export const flymeIconNames: Record<string, string> = {")
    for cp, name in sorted(FLYME_ICON_NAMES.items(), key=lambda kv: kv[1]):
        lines.append(f"  {json.dumps(name)}: {json.dumps(cp)},")
    lines.append("};")
    lines.append("")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote", out, len(lines), "lines")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
