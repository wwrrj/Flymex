"""Emit Flymex Android `values` resources from the extracted Flyme token database.

Every resource keeps its original Flyme name (fd_sys_color_*, mz_*, mc_*, Blue_*), so the
library is a 1:1 mirror of what Flyme 12.6 ships, and the values are copied verbatim.

Usage: python -I tools/gen-android-res.py <flyme-tokens.json> <library-res-dir>
"""
import json, os, re, sys

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- AUTO-GENERATED by tools/gen-android-res.py from Flyme 12.6.0.0A (meizu 21 Pro) system resources. Do not edit. -->\n'
COLOR_HEX = re.compile(r'^#[0-9a-fA-F]{3,8}$')
NAME_OK = re.compile(r'^[A-Za-z0-9_.]+$')
# Resources from Material/AppCompat/SettingsLib that leaked into the DB via generic names.
SKIP = re.compile(r'^(m3_|mtrl_|abc_|design_|settingslib_|material_|cardview_|contextual_)')

INTEGERS = [
    'bottom_dialog_anim_duration', 'bottom_sheet_slide_duration', 'config_actionbarAnimationTime',
    'config_appAnimTime', 'config_fragmentAnimTime', 'config_fragmentAlphaAnimTime', 'config_tooltipAnimTime',
    'config_editNewAnimTime', 'config_dialogShowAnimationDurationMs', 'config_dialogHideAnimationDurationMs',
]


def fmt_dimen(value):
    m = re.match(r'^(-?[\d.]+)\s*([a-z%]*)$', value.strip())
    if not m:
        return value.strip()
    num, unit = float(m.group(1)), m.group(2)
    s = f'{num:.4f}'.rstrip('0').rstrip('.')
    if s in ('', '-0'):
        s = '0'
    if unit in ('dip', 'dp'):
        return f'{s}dp'
    if unit in ('sp', 'px', 'pt', 'mm', 'in'):
        return f'{s}{unit}'
    return s


def main(db_path, res_dir):
    db = json.load(open(db_path, encoding='utf-8'))['tokens']
    light_colors, night_colors, dimens, night_dimens, strings, integers = {}, {}, {}, {}, {}, {}
    color_names = set()

    for name, tok in db.items():
        if SKIP.match(name) or not NAME_OK.match(name):
            continue
        l, n = tok.get('light'), tok.get('night')
        e = l or n
        if not e:
            continue
        typ = e['type']
        v = e['value'].strip()
        if typ == 'color':
            if COLOR_HEX.match(v) or v.startswith('@color/') or v.startswith('@android:color/'):
                color_names.add(name)
        elif typ == 'dimen' or (typ == 'item' and 'number' in e):
            pass

    for name, tok in db.items():
        if SKIP.match(name) or not NAME_OK.match(name):
            continue
        l, n = tok.get('light'), tok.get('night')
        e = l or n
        typ = e['type']
        lv = l['value'].strip() if l else None
        nv = n['value'].strip() if n else None
        if typ == 'color':
            def ok(v):
                if v is None:
                    return None
                if COLOR_HEX.match(v):
                    return v
                if v.startswith('@android:color/'):
                    return v
                if v.startswith('@color/'):
                    ref = v.split('/')[-1]
                    return v if ref in color_names else None
                return None
            lc, nc = ok(lv), ok(nv)
            if lc is None and nc is None:
                continue
            light_colors[name] = lc if lc is not None else nc
            if nc is not None and nc != lc:
                night_colors[name] = nc
        elif typ == 'dimen' or (typ == 'item' and 'number' in e and l):
            if lv is None:
                continue
            if lv.startswith('@'):
                ref = lv.split('/')[-1]
                dimens[name] = (lv if ref in db else None)
                if dimens[name] is None:
                    del dimens[name]
                continue
            if typ == 'item' and re.match(r'^[\d.]+$', lv):
                dimens[name] = ('item', lv)   # fractional <item type="dimen">
            else:
                dimens[name] = fmt_dimen(lv)
            if nv and nv != lv and not nv.startswith('@'):
                night_dimens[name] = fmt_dimen(nv)
        elif typ == 'string' and name.startswith('fd_sys_type'):
            strings[name] = lv
        elif typ == 'integer' and name in INTEGERS:
            integers[name] = lv

    def write(path, body):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(HEADER + '<resources>\n' + body + '</resources>\n')

    write(os.path.join(res_dir, 'values', 'flymex_colors.xml'),
          ''.join(f'    <color name="{k}">{v}</color>\n' for k, v in sorted(light_colors.items())))
    write(os.path.join(res_dir, 'values-night', 'flymex_colors.xml'),
          ''.join(f'    <color name="{k}">{v}</color>\n' for k, v in sorted(night_colors.items())))

    def dimen_line(k, v):
        if isinstance(v, tuple):
            return f'    <item name="{k}" type="dimen" format="float">{v[1]}</item>\n'
        return f'    <dimen name="{k}">{v}</dimen>\n'
    write(os.path.join(res_dir, 'values', 'flymex_dimens.xml'), ''.join(dimen_line(k, v) for k, v in sorted(dimens.items())))
    if night_dimens:
        write(os.path.join(res_dir, 'values-night', 'flymex_dimens.xml'), ''.join(dimen_line(k, v) for k, v in sorted(night_dimens.items())))
    write(os.path.join(res_dir, 'values', 'flymex_strings.xml'),
          ''.join(f'    <string name="{k}" translatable="false">{v}</string>\n' for k, v in sorted(strings.items())))
    write(os.path.join(res_dir, 'values', 'flymex_integers.xml'),
          ''.join(f'    <integer name="{k}">{v}</integer>\n' for k, v in sorted(integers.items())))
    print(f'colors: {len(light_colors)} (night overrides {len(night_colors)})  dimens: {len(dimens)} (night {len(night_dimens)})  strings: {len(strings)}  integers: {len(integers)}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
